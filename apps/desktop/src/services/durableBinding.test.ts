function depsReturning(thread: BeadComment[]): DurableBindingDeps & { readComments: ReturnType<typeof vi.fn> } {
  const readComments = vi.fn(async () => thread);
  return { readComments } as never;
}

const RECORD = handoffRecordComment({
  agentId: "build-durable",
  projectId: "proj-durable",
  beadId: "e1.t1",
  at: 1_788_000_000_000,
});

describe("resolveOrchestratorBinding — LIVE STRICTLY OUTRANKS DURABLE", () => {
  it("reports source:'live' when a roster row exists, EVEN WITH a durable record present", () => {
    const deps = depsReturning([comment(RECORD)]);
    return resolveOrchestratorBinding(
      {
        projectPath: "/repo",
        beadId: "e1.t1",
        live: { id: "build-live", name: "Live Orchestrator" },
        handedToBuild: true,
      },
      deps,
    ).then((got) => {
      expect(got).toEqual({ source: "live", agentId: "build-live", name: "Live Orchestrator" });
      // THE COST HALF OF THE SAME RULE, asserted separately: live wins BEFORE the read, so the
      // contended detail call never happens. A mutant that reorders the two would still return a
      // live-looking answer here; only this assertion catches it.
      expect(deps.readComments).not.toHaveBeenCalled();
    });
  });

  it("recovers source:'durable' when the row is gone and the bead carries the record", async () => {
    const deps = depsReturning([comment(RECORD)]);
    const got = await resolveOrchestratorBinding(
      { projectPath: "/repo", beadId: "e1.t1", live: null, handedToBuild: true },
      deps,
    );
    expect(got).toEqual({
      source: "durable",
      agentId: "build-durable",
      projectId: "proj-durable",
      at: 1_788_000_000_000,
    });
    expect(deps.readComments).toHaveBeenCalledWith("/repo", "e1.t1");
  });

  // THE PAIRED NEGATIVE. Recovery alone is ambiguous — absence passes for a fixed and an unfixed
  // reader alike — so the two are asserted together.
  it("acquires NO binding for a bead that was never handed to Build, and spends no read", async () => {
    const deps = depsReturning([comment(RECORD)]);
    const got = await resolveOrchestratorBinding(
      { projectPath: "/repo", beadId: "e1.t2", live: null, handedToBuild: false },
      deps,
    );
    expect(got).toBeNull();
    expect(deps.readComments).not.toHaveBeenCalled();
  });

  it("is null for a labelled bead whose thread holds no handoff record", async () => {
    const deps = depsReturning([comment("Just a human note.")]);
    expect(
      await resolveOrchestratorBinding(
        { projectPath: "/repo", beadId: "e1.t3", live: null, handedToBuild: true },
        deps,
      ),
    ).toBeNull();
  });

  it("swallows a failed read rather than rejecting into the caller's plan read", async () => {
    const readComments = vi.fn(async () => {
      throw new Error("bd is locked");
    });
    await expect(
      resolveOrchestratorBinding(
        { projectPath: "/repo", beadId: "e1.t4", live: null, handedToBuild: true },
        { readComments } as never,
      ),
    ).resolves.toBeNull();
  });

  it("recovers from a PROSE-ONLY thread — the records already on origin/main", async () => {
    const deps = depsReturning([comment(proseOnly("build-legacy", "proj-legacy"))]);
    expect(
      await resolveOrchestratorBinding(
        { projectPath: "/repo", beadId: "e1.t5", live: null, handedToBuild: true },
        deps,
      ),
    ).toEqual({
      source: "durable",
      agentId: "build-legacy",
      projectId: "proj-legacy",
      at: null,
    });
  });
});
